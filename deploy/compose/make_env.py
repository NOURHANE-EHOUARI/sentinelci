"""Create deploy/compose/.env with random credentials for the local platform.

The file is git-ignored and written with owner-only permissions. An existing file is never overwritten, so
`make up` can call this every time without rotating credentials under running containers.
"""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

ENV_FILE = Path(__file__).resolve().parent / ".env"

# Values use only [A-Za-z0-9_-]: safe inside URLs and never interpolated by Compose.
VARIABLES = {
    "POSTGRES_PASSWORD": lambda: secrets.token_urlsafe(32),
    "REDIS_PASSWORD": lambda: secrets.token_urlsafe(32),
    "S3_ACCESS_KEY": lambda: "sentinel-" + secrets.token_hex(8),
    "S3_SECRET_KEY": lambda: secrets.token_urlsafe(32),
    "GRAFANA_ADMIN_PASSWORD": lambda: secrets.token_urlsafe(24),
}


def write_env(path: Path = ENV_FILE) -> bool:
    """Write a new env file and return True, or return False if one already exists."""
    lines = ["# Generated by deploy/compose/make_env.py. Local credentials only: never commit this file.\n"]
    lines += [f"{name}={generate()}\n" for name, generate in VARIABLES.items()]
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.writelines(lines)
    return True


if __name__ == "__main__":
    created = write_env()
    print(f"{'created' if created else 'kept existing'} {ENV_FILE}", file=sys.stderr)
