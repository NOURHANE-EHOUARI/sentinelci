"""Create deploy/compose/.env with random credentials for the local platform.

The file is git-ignored and written with owner-only permissions. An existing value is never changed, so
`make up` can call this every time without rotating credentials under running containers; variables added
since the file was written are appended.
"""

from __future__ import annotations

import hashlib
import os
import secrets
import sys
from pathlib import Path

ENV_FILE = Path(__file__).resolve().parent / ".env"

# Values use only [A-Za-z0-9_-]: safe inside URLs and never interpolated by Compose.
VARIABLES = {
    "POSTGRES_PASSWORD": lambda: secrets.token_urlsafe(32),
    # The worker's own database login (`sentinel_worker`, migration 0011): only what its jobs need.
    "WORKER_DATABASE_PASSWORD": lambda: secrets.token_urlsafe(32),
    "REDIS_PASSWORD": lambda: secrets.token_urlsafe(32),
    "S3_ACCESS_KEY": lambda: "sentinel-" + secrets.token_hex(8),
    "S3_SECRET_KEY": lambda: secrets.token_urlsafe(32),
    "GRAFANA_ADMIN_PASSWORD": lambda: secrets.token_urlsafe(24),
    # Bearer token of the platform's ingestion clients (B1). Clients send it; the API only gets its hash.
    "SENTINEL_API_TOKEN": lambda: secrets.token_urlsafe(32),
}

# Values computed from the generated ones, by name.
DERIVED = {
    "SENTINEL_API_TOKEN_SHA256": lambda values: hashlib.sha256(
        values["SENTINEL_API_TOKEN"].encode()
    ).hexdigest(),
}

# Values for the clients on the host only: compose.yaml must never pass them to a container.
CLIENT_ONLY = frozenset({"SENTINEL_API_TOKEN"})
# What compose.yaml reads from the file.
COMPOSE_VARIABLES = (set(VARIABLES) | set(DERIVED)) - CLIENT_ONLY


class EnvError(ValueError):
    """The existing file is inconsistent; nothing is written."""


def _existing(path: Path) -> dict[str, str] | None:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    return dict(
        line.split("=", 1) for line in text.splitlines() if "=" in line and not line.lstrip().startswith("#")
    )


def write_env(path: Path = ENV_FILE) -> bool:
    """Write the env file, or add the variables an older one lacks. Return True if anything was written.

    An existing value is never changed: rotating a credential under running containers would lock them out.
    """
    existing = _existing(path)
    values = dict(existing or {})
    for name, generate in VARIABLES.items():
        values.setdefault(name, generate())
    for name, derive in DERIVED.items():
        values.setdefault(name, derive(values))
        # A list (an overlapping rotation) is fine as long as it holds the current value. Only the token line
        # deleted to rotate it would leave the old hash alone, and refuse every write.
        if derive(values) not in values[name].split(","):
            raise EnvError(f"{name} in {path} does not match its source; delete both lines to rotate them")
    missing = [name for name in [*VARIABLES, *DERIVED] if existing is None or name not in existing]
    if not missing:
        return False
    lines = [f"{name}={values[name]}\n" for name in missing]
    if existing is None:
        lines.insert(
            0, "# Generated by deploy/compose/make_env.py. Local credentials only: never commit this file.\n"
        )
        try:
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        except FileExistsError:  # created meanwhile: leave it to the next run
            return False
    else:
        if not path.read_bytes().endswith(b"\n") and path.stat().st_size:
            lines.insert(0, "\n")
        fd = os.open(path, os.O_WRONLY | os.O_APPEND)
    with os.fdopen(fd, "a" if existing is not None else "w", encoding="utf-8", newline="\n") as handle:
        handle.writelines(lines)
    return True


if __name__ == "__main__":
    try:
        created = write_env()
    except EnvError as exc:
        print(f"make_env: {exc}", file=sys.stderr)
        raise SystemExit(3) from exc
    print(f"{'wrote' if created else 'kept existing'} {ENV_FILE}", file=sys.stderr)
